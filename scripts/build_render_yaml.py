"""Generate the root render.yaml (one Blueprint for all 15 services). Re-run after changing a service list or setting.

  python scripts/build_render_yaml.py [--account 141571819444] [--region frankfurt]

Design:
  - non-secret settings live in the Blueprint env group `cleandocs-config`
  - secrets live in env groups you create in the Render dashboard BEFORE syncing the Blueprint (Render does not prompt for
    values inside Blueprint env groups): cleandocs-auth, cleandocs-aws-ingest, cleandocs-aws-processing, cleandocs-aws-indexing
  - each service gets exactly one AWS tier (least privilege): ingest, processing or indexing
  - autoDeploy is off: every service shares `shared/`, so a push would rebuild all 15 images and burn free build minutes
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# service -> (AWS tier, extra env vars)
SERVICES: dict[str, tuple[str, dict[str, str]]] = {
    "upload": ("ingest", {"STEP_FUNCTIONS_INGESTION_ARN": "{ingestion_arn}", "MAX_FILE_SIZE_MB": "25"}),
    "validation": ("processing", {"MAX_FILE_SIZE_MB": "25", "MAX_PDF_PAGES": "300"}),
    "archive": ("ingest", {"MAX_FILE_SIZE_MB": "25", "MAX_ARCHIVE_EXPANDED_SIZE_MB": "100", "MAX_ARCHIVE_FILE_COUNT": "50", "MAX_ARCHIVE_DEPTH": "0"}),
    "manifest": ("processing", {}),
    "normalization": ("processing", {}),
    "cleaning": ("processing", {}),
    "duplicate": ("processing", {}),
    "extraction": ("processing", {"OCR_ENABLED": "true", "TEXTRACT_MONTHLY_PAGE_CAP": "300", "OCR_PAGES_PER_CALL": "4"}),
    "metadata": ("processing", {}),
    "chunking": ("processing", {"CHUNK_TARGET_CHARS": "1200", "CHUNK_MAX_CHARS": "1800", "CHUNK_OVERLAP_CHARS": "150"}),
    "embedding": ("processing", {}),
    "vector-indexing": ("indexing", {"BEDROCK_KNOWLEDGE_BASE_ID": "NEYHRDRGOT", "BEDROCK_DATA_SOURCE_ID": "FWC2ZGVLIT"}),
    "reconciliation": ("indexing", {"BEDROCK_KNOWLEDGE_BASE_ID": "NEYHRDRGOT", "BEDROCK_DATA_SOURCE_ID": "FWC2ZGVLIT"}),
    "entity-extraction": ("processing", {}),
    "graph": ("processing", {}),
}
SECRET_GROUPS = ["cleandocs-auth", "cleandocs-aws-ingest", "cleandocs-aws-processing", "cleandocs-aws-indexing"]


def render(account: str, region: str, render_region: str) -> str:
    bucket = f"cleandocs-{account}-{region}"
    ingestion_arn = f"arn:aws:states:{region}:{account}:stateMachine:cleandocs-ingestion"
    out = [
        "# GENERATED by scripts/build_render_yaml.py - edit the script, not this file.",
        "# Create the four secret env groups in the Render dashboard first (docs/deploy-render.md), then sync this Blueprint.",
        "envVarGroups:",
        "  - name: cleandocs-config",
        "    envVars:",
        f"      - {{ key: AWS_REGION, value: {region} }}",
        f"      - {{ key: S3_BUCKET, value: {bucket} }}",
        "      - { key: DYNAMODB_REGISTRY_TABLE, value: cleandocs-registry }",
        "      - { key: DYNAMODB_INGEST_TRAIL_TABLE, value: document-ingest-trail }",
        "      - { key: LOG_LEVEL, value: INFO }",
        "services:",
    ]
    for svc, (tier, extra) in SERVICES.items():
        out += [
            "  - type: web", f"    name: cleandocs-{svc}-service", "    runtime: docker", "    plan: free",
            f"    region: {render_region}", f"    dockerfilePath: ./services/{svc}-service/Dockerfile", "    dockerContext: .",
            "    healthCheckPath: /health/live", "    autoDeploy: false", "    envVars:",
            "      - fromGroup: cleandocs-config", "      - fromGroup: cleandocs-auth", f"      - fromGroup: cleandocs-aws-{tier}",
        ]
        for k, v in extra.items():
            out.append(f'      - {{ key: {k}, value: "{v.format(ingestion_arn=ingestion_arn)}" }}')
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--account", default="141571819444")
    ap.add_argument("--aws-region", default="eu-west-1")
    ap.add_argument("--region", default="frankfurt", help="Render region (closest to eu-west-1)")
    a = ap.parse_args()
    (ROOT / "render.yaml").write_text(render(a.account, a.aws_region, a.region), encoding="utf-8", newline="\n")
    print(f"wrote render.yaml ({len(SERVICES)} services)")
